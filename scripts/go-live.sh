#!/usr/bin/env bash
#
# go-live.sh — ONE command from fresh Ubuntu to a running AI Hub (Compose-only,
# no Coolify). Run ON THE VPS (hPanel Browser terminal or SSH), as root/sudo:
#
#   curl -fsSL https://raw.githubusercontent.com/starkvisionz/Ai-hub/main/scripts/go-live.sh -o go-live.sh
#   sudo bash go-live.sh
#
# What it does (idempotent — safe to re-run):
#   1. Base packages + SSH-only firewall
#   2. Docker Engine + Compose plugin
#   3. Tailscale (runs `tailscale up` if the node isn't in a tailnet yet —
#      follow the printed login URL, then the script continues)
#   4. Clone/update the repo at /opt/ai-hub (tracks origin/main)
#   5. First run only: generate .env — random secrets (code-server password,
#      Postgres password, n8n key, hub API token) + BIND_ADDR=<tailscale ip>
#   6. Build + start the stack, gate on the hub app's healthcheck
#   7. Print your service URLs and the generated credentials
#
# Backups (restic) are opt-in: set RESTIC_* in /opt/ai-hub/.env, then
#   docker compose --profile backup up -d
#
# No secrets live in this script; generated ones are written only to the
# git-ignored /opt/ai-hub/.env on the box.

set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/starkvisionz/Ai-hub.git}"
DIR="${DIR:-/opt/ai-hub}"

log() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }

if [[ $EUID -ne 0 ]]; then
  echo "Run as root: sudo bash go-live.sh" >&2
  exit 1
fi

log "1/6  Base packages + firewall (SSH-only)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -y >/dev/null
apt-get install -y curl git ufw ca-certificates openssl >/dev/null
ufw allow OpenSSH >/dev/null
ufw --force enable >/dev/null
echo "firewall: SSH only — services ride the tailnet, never the public IP"

log "2/6  Docker Engine"
if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker >/dev/null 2>&1 || true
docker compose version

log "3/6  Tailscale"
if ! command -v tailscale >/dev/null 2>&1; then
  curl -fsSL https://tailscale.com/install.sh | sh
fi
if ! TSIP="$(tailscale ip -4 2>/dev/null | head -1)" || [ -z "$TSIP" ]; then
  echo "This node isn't in your tailnet yet — follow the login URL below."
  tailscale up
  TSIP="$(tailscale ip -4 | head -1)"
fi
echo "tailscale ip: ${TSIP}"

log "4/6  Repo at ${DIR} (tracking origin/main)"
if [ -d "${DIR}/.git" ]; then
  git -C "$DIR" fetch origin main
  git -C "$DIR" reset --hard origin/main
else
  git clone "$REPO_URL" "$DIR"
fi
cd "$DIR"

log "5/6  Configuration (.env)"
if [ -f .env ]; then
  echo ".env already exists — keeping it (secrets are never regenerated)."
  # Keep BIND_ADDR current if the tailscale ip changed.
  if grep -q '^BIND_ADDR=' .env; then
    sed -i "s|^BIND_ADDR=.*|BIND_ADDR=${TSIP}|" .env
  else
    echo "BIND_ADDR=${TSIP}" >> .env
  fi
else
  umask 077
  CODE_PW="$(openssl rand -hex 16)"
  PG_PW="$(openssl rand -hex 24)"
  N8N_KEY="$(openssl rand -hex 32)"
  API_TOKEN="$(openssl rand -hex 32)"
  cat > .env <<EOF
# Generated by go-live.sh on $(date -u +%FT%TZ) — git-ignored. Full reference:
# .env.example. Backups: set RESTIC_* then: docker compose --profile backup up -d
BIND_ADDR=${TSIP}
TZ=UTC
CODE_SERVER_PASSWORD=${CODE_PW}
POSTGRES_USER=aihub
POSTGRES_PASSWORD=${PG_PW}
POSTGRES_DB=aihub
DATABASE_URL=postgres://aihub:${PG_PW}@postgres:5432/aihub
N8N_ENCRYPTION_KEY=${N8N_KEY}
N8N_HOST=${TSIP}
N8N_WEBHOOK_URL=http://${TSIP}:5678/
HOMEPAGE_ALLOWED_HOSTS=${TSIP}:3001,localhost:3001
HUB_API_TOKEN=${API_TOKEN}
SVC_CODE_SERVER_URL=http://${TSIP}:8080
SVC_N8N_URL=http://${TSIP}:5678
SVC_HOMEPAGE_URL=http://${TSIP}:3001
EOF
  echo ".env written with generated secrets (shown once at the end)."
fi

log "6/6  Build + start the stack"
docker compose config -q
docker compose up -d --build --remove-orphans

echo "waiting for the hub app to report healthy…"
healthy=0
for i in $(seq 1 60); do
  status="$(docker inspect -f '{{.State.Health.Status}}' ai-hub-app 2>/dev/null || echo starting)"
  if [ "$status" = "healthy" ]; then healthy=1; break; fi
  sleep 2
done
if [ "$healthy" -ne 1 ]; then
  echo "!! hub app did not become healthy — current state:" >&2
  docker compose ps
  docker compose logs --tail 40 hub-app >&2 || true
  exit 1
fi
docker compose ps

CODE_PW_NOW="$(grep '^CODE_SERVER_PASSWORD=' .env | cut -d= -f2-)"
TOKEN_NOW="$(grep '^HUB_API_TOKEN=' .env | cut -d= -f2-)"
cat <<DONE

────────────────────────────────────────────────────────────────────────
  ✅ AI HUB IS LIVE — reachable from any device on your tailnet:

    Hub app / command center   http://${TSIP}:3000   (agents: /agents)
    code-server (IDE)          http://${TSIP}:8080
    n8n (automation)           http://${TSIP}:5678
    Homepage (dashboard)       http://${TSIP}:3001
    Postgres (brain)           ${TSIP}:5432

  Credentials (stored in ${DIR}/.env — save these somewhere safe):
    code-server password:  ${CODE_PW_NOW}
    hub API token:         ${TOKEN_NOW}

  Agents report in with:
    export HUB_URL=http://${TSIP}:3000 HUB_API_TOKEN=${TOKEN_NOW}
    ${DIR}/scripts/agent-report.sh heartbeat claude-code claude-code "task"

  Updates after each merge to main:   bash ${DIR}/scripts/deploy-compose.sh
  Off-site backups (recommended):     set RESTIC_* in .env, then
                                      docker compose --profile backup up -d
  Also do: switch SSH to key auth; take an hPanel snapshot.
────────────────────────────────────────────────────────────────────────
DONE
